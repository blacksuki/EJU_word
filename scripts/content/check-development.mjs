import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'../..');
const readJson=async name=>JSON.parse(await readFile(path.join(root,name),'utf8'));
const bundle=await readJson('public/content/development.json');
assert.equal(bundle.purpose,'personal_study');
const review=await readJson('content/reviews/human-listening-2026-11-05.json');
assert.deepEqual(bundle.humanAudioReview,review);
assert.equal(review.method,'human_listening');
assert.equal(review.reviewer,'user');
assert.equal(review.assets.length,10);
assert.equal(new Set(review.assets.map(a=>a.id)).size,10);
assert.equal(bundle.items.length,5);
assert.equal(bundle.assets.length,10);
assert.deepEqual(bundle.items,await readJson('content/entries.json'));
let bytes=0;const results=[];
for(const asset of bundle.assets){
 assert.equal(asset.status,'human_accepted');
 assert.ok(review.assets.some(a=>a.id===asset.id&&a.sha256===asset.sha256));
 assert.match(asset.url,/^\/audio\/[a-z0-9-]+\.mp3$/);
 const item=bundle.items.find(i=>i.id===asset.itemId);
 assert.ok(item && item.audio[asset.role]===asset.id);
 assert.equal(asset.text,asset.role==='listen'?item.listenText:item.exampleJa);
 const file=path.join(root,'public',asset.url);
 const data=await readFile(file);
 assert.equal(data.length,asset.bytes);
 assert.equal(createHash('sha256').update(data).digest('hex'),asset.sha256);
 const probe=spawnSync('ffprobe',['-v','error','-show_entries','format=duration','-of','json',file],{encoding:'utf8'});
 assert.equal(probe.status,0,probe.error?.message||probe.stderr);
 const duration=Number(JSON.parse(probe.stdout).format.duration);
 assert.ok(duration>0 && duration<30);
 const decode=spawnSync('ffmpeg',['-v','error','-i',file,'-f','null','-'],{encoding:'utf8'});
 assert.equal(decode.status,0,decode.error?.message||decode.stderr);
 bytes+=data.length;results.push({id:asset.id,duration,bytes:data.length,decode:'PASS'});
}
const originals=await readJson('artifacts/verification/original-files.json');
for(const [file,hash] of Object.entries(originals)) assert.equal(createHash('sha256').update(await readFile(path.join(root,file))).digest('hex'),hash,`Original changed: ${file}`);
console.log(JSON.stringify({status:'PASS',purpose:bundle.purpose,items:5,assets:10,totalBytes:bytes,originalsUnchanged:Object.keys(originals).length,audioReview:'HUMAN_ACCEPTED_USER_REPORT',independentAiAudioReview:'NOT_RUN',results},null,2));
